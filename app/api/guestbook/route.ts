import { createHash } from "node:crypto";
import { getDatabase } from "@/lib/neon";
import { isMilkOwner } from "@/lib/auth/server";

export const dynamic = "force-dynamic";

type GuestbookRow = { id: string; name: string; message: string; created_at: string };

async function ensureTables() {
  const sql = getDatabase();
  await sql`CREATE TABLE IF NOT EXISTS guestbook_messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(48) NOT NULL,
    message VARCHAR(500) NOT NULL,
    rate_key CHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`;
  await sql`CREATE INDEX IF NOT EXISTS guestbook_messages_created_at_idx ON guestbook_messages (created_at DESC)`;
  await sql`CREATE INDEX IF NOT EXISTS guestbook_messages_rate_key_created_at_idx ON guestbook_messages (rate_key, created_at DESC)`;
  await sql`UPDATE guestbook_messages SET rate_key=NULL WHERE created_at < NOW() - INTERVAL '30 days' AND rate_key IS NOT NULL`;
  await sql`CREATE TABLE IF NOT EXISTS guestbook_archives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_count INTEGER NOT NULL,
    entries JSONB NOT NULL,
    archived_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`;
  return sql;
}

function clientRateKey(request: Request) {
  const forwarded = request.headers.get("x-forwarded-for")?.split(",")[0]?.trim();
  const address = forwarded || request.headers.get("x-real-ip") || "unknown";
  return createHash("sha256").update(`${process.env.DATABASE_URL}:${address}`).digest("hex");
}

async function archiveOldEntries(sql: ReturnType<typeof getDatabase>) {
  // Keep the latest 500 live. Once the book grows beyond 1,000 entries,
  // move the oldest 500 into compact JSONB archive records in the same DB.
  await sql`
    WITH total AS MATERIALIZED (
      SELECT COUNT(*)::int AS amount FROM guestbook_messages
    ), old_entries AS MATERIALIZED (
      SELECT id, name, message, created_at
      FROM guestbook_messages
      WHERE (SELECT amount FROM total) > 1000
      ORDER BY created_at ASC
      LIMIT 500
      FOR UPDATE SKIP LOCKED
    ), archived AS (
      INSERT INTO guestbook_archives (entry_count, entries)
      SELECT COUNT(*)::int,
        COALESCE(jsonb_agg(jsonb_build_object('id', id, 'name', name, 'message', message, 'createdAt', created_at) ORDER BY created_at), '[]'::jsonb)
      FROM old_entries
      HAVING COUNT(*) > 0
      RETURNING id
    )
    DELETE FROM guestbook_messages
    WHERE id IN (SELECT id FROM old_entries)
  `;
}

export async function GET() {
  try {
    const sql = await ensureTables();
    const rows = await sql`SELECT id, name, message, created_at FROM guestbook_messages ORDER BY created_at DESC LIMIT 200` as GuestbookRow[];
    return Response.json({ entries: rows.map((row) => ({ id: row.id, name: row.name, message: row.message, createdAt: row.created_at })), canModerate: await isMilkOwner() }, { headers: { "Cache-Control": "no-store" } });
  } catch (error) {
    console.error("Unable to load the guestbook", error);
    return Response.json({ error: "The guestbook is temporarily unavailable." }, { status: 500 });
  }
}

export async function POST(request: Request) {
  try {
    const input = await request.json() as { name?: unknown; message?: unknown; website?: unknown };
    // Quietly accept honeypot submissions without storing them.
    if (typeof input.website === "string" && input.website.trim()) return Response.json({ accepted: true }, { status: 201 });
    const name = typeof input.name === "string" ? input.name.trim().replace(/\s+/g, " ") : "";
    const message = typeof input.message === "string" ? input.message.trim() : "";
    if (!name || name.length > 48 || !message || message.length > 500) {
      return Response.json({ error: "Add a name (up to 48 characters) and a comment (up to 500 characters)." }, { status: 400 });
    }
    const sql = await ensureTables();
    const rateKey = clientRateKey(request);
    const recent = await sql`SELECT COUNT(*)::int AS amount FROM guestbook_messages WHERE rate_key=${rateKey} AND created_at > NOW() - INTERVAL '10 minutes'` as Array<{ amount: number }>;
    if ((recent[0]?.amount ?? 0) >= 3) return Response.json({ error: "Please wait a few minutes before signing again." }, { status: 429, headers: { "Retry-After": "600" } });
    const rows = await sql`INSERT INTO guestbook_messages (name,message,rate_key) VALUES (${name},${message},${rateKey}) RETURNING id,name,message,created_at` as GuestbookRow[];
    await archiveOldEntries(sql);
    const row = rows[0];
    return Response.json({ entry: { id: row.id, name: row.name, message: row.message, createdAt: row.created_at } }, { status: 201 });
  } catch (error) {
    console.error("Unable to sign the guestbook", error);
    return Response.json({ error: "Your message could not be saved right now. Please try again." }, { status: 500 });
  }
}

export async function DELETE(request: Request) {
  if (!await isMilkOwner()) return Response.json({ error: "Unauthorized" }, { status: 401 });
  try {
    const input = await request.json() as { id?: unknown };
    if (typeof input.id !== "string") return Response.json({ error: "Invalid entry." }, { status: 400 });
    const sql = await ensureTables();
    await sql`DELETE FROM guestbook_messages WHERE id=${input.id}`;
    return new Response(null, { status: 204 });
  } catch (error) {
    console.error("Unable to moderate the guestbook", error);
    return Response.json({ error: "The entry could not be removed." }, { status: 500 });
  }
}
